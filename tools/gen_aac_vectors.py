"""Generate AAC decoder test vectors from ffmpeg.

ffmpeg encodes a sine to AAC-LC in ADTS frames and decodes it back to PCM. The test feeds the
ADTS bytes to the radio's AAC decoder (src/core/radio/stream/AacDecoder.cpp) and compares a
window of its output with ffmpeg's, allowing for the encoder delay. A few hundred milliseconds
per vector keep the file small.

    python tools/gen_aac_vectors.py

Writes test/test_aacdecoder/vectors.h. Requires ffmpeg on PATH. ffmpeg's own encoder makes
AAC-LC only; HE-AAC is covered by the decoder library's own conformance and by a station test.
"""

import os
import struct
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "test", "test_aacdecoder", "vectors.h")
WINDOW = 2048
SKIP = 4096

VECTORS = [
    ("lc_stereo_44k", "sine=frequency=1000:sample_rate=44100:duration=0.4", 2, 44100, "96k"),
    ("lc_mono_22k", "sine=frequency=440:sample_rate=22050:duration=0.6", 1, 22050, "32k"),
    ("lc_stereo_48k", "sine=frequency=700:sample_rate=48000:duration=0.4", 2, 48000, "128k"),
]


def wrap(values, fmt):
    items = [fmt % v for v in values]
    lines = [", ".join(items[i:i + 16]) for i in range(0, len(items), 16)]
    return "\n    " + ",\n    ".join(lines) + "\n"


def run(args):
    subprocess.run(args, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def main():
    parts = ["// GENERATED by tools/gen_aac_vectors.py -- DO NOT EDIT.\n//\n// AAC-LC in ADTS, encoded and decoded by ffmpeg. `pcm` holds %d frames of the reference decode,\n// starting %d frames in.\n#pragma once\n\n#include <cstddef>\n#include <cstdint>\n\nnamespace aacvectors {\n\n" % (WINDOW, SKIP)]
    entries = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, source, channels, rate, bitrate in VECTORS:
            aac = os.path.join(tmp, name + ".aac")
            pcm = os.path.join(tmp, name + ".pcm")
            run(["ffmpeg", "-hide_banner", "-f", "lavfi", "-i", source, "-ac", str(channels), "-c:a", "aac",
                 "-b:a", bitrate, "-f", "adts", "-y", aac])
            run(["ffmpeg", "-hide_banner", "-i", aac, "-f", "s16le", "-ac", str(channels), "-y", pcm])
            data = open(aac, "rb").read()
            ref = open(pcm, "rb").read()
            samples = struct.unpack("<%dh" % (len(ref) // 2), ref)
            window = samples[SKIP * channels:(SKIP + WINDOW) * channels]
            parts.append("// %s: %d Hz, %d ch, %d bytes encoded\n" % (name, rate, channels, len(data)))
            parts.append("inline constexpr uint8_t k_%s_aac[] = {%s};\n" % (name, wrap(data, "0x%02X")))
            parts.append("inline constexpr int16_t k_%s_pcm[] = {%s};\n\n" % (name, wrap(window, "%d")))
            entries.append('  {"%s", k_%s_aac, sizeof(k_%s_aac), k_%s_pcm, %d, %d, %d},\n'
                           % (name, name, name, name, len(window) // channels, channels, rate))
    parts.append("inline constexpr int kWindowFrames = %d;\ninline constexpr int kSkipFrames = %d;\n\n" % (WINDOW, SKIP))
    parts.append("struct AacVector {\n  const char* name;\n  const uint8_t* aac;\n  std::size_t aacBytes;\n"
                 "  const int16_t* pcm;\n  int frames;\n  int channels;\n  int rate;\n};\n\n")
    parts.append("inline constexpr AacVector kAacVectors[] = {\n%s};\n\n}  // namespace aacvectors\n" % "".join(entries))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("".join(parts))
    print(OUT)


if __name__ == "__main__":
    main()
